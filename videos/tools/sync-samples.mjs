#!/usr/bin/env node
/**
 * Runs every project in ../samples, captures its real console output and
 * generates `tutorials/src/samples.generated.ts` with:
 *
 * - the numbered sections of each Program.cs (`// ── N. Title ───`),
 * - the text files of its input/ folder,
 * - its captured stdout and the text files it wrote to output/.
 *
 * PNG outputs are copied to tutorials/public/samples/<project>/.
 * The tutorial videos show code and output only from this file, so what is
 * on screen is exactly what the samples compile and print.
 *
 *   node tools/sync-samples.mjs            # run all samples
 *   node tools/sync-samples.mjs --no-run   # regenerate from the last capture
 *
 * 05-browsing needs AngleSharp.Infrastructure.TestSite on http://localhost:8080.
 */
import {execFileSync} from 'node:child_process';
import {copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const samplesDir = join(here, '..', '..', 'samples');
const tutorialsDir = join(here, '..', 'tutorials');
const run = !process.argv.includes('--no-run');

const files = (dir, filter) =>
  existsSync(dir)
    ? readdirSync(dir, {recursive: true})
        .map((f) => join(dir, f))
        .filter((f) => statSync(f).isFile() && filter(f))
    : [];
const isText = (f) => /\.(html|xml|xsd|svg|json|txt|xhtml|css)$/.test(f);

const result = {};
for (const name of readdirSync(samplesDir).filter((d) => /^\d\d-/.test(d)).sort()) {
  const dir = join(samplesDir, name);
  const capture = join(dir, 'output', 'stdout.txt');
  if (run) {
    console.log(`Running ${name}…`);
    const stdout = execFileSync('dotnet', ['run', '--', ...(name === '05-browsing' ? ['http://localhost:8080'] : [])], {
      cwd: dir,
      encoding: 'utf8',
      timeout: 300_000,
    });
    mkdirSync(join(dir, 'output'), {recursive: true});
    writeFileSync(capture, stdout);
  }
  if (!existsSync(capture)) {
    throw new Error(`No captured output for ${name}. Run without --no-run first.`);
  }

  const program = readFileSync(join(dir, 'Program.cs'), 'utf8').replace(/\r\n/g, '\n');
  const sections = {};
  // A numbered marker starts a section; any `// ──` marker (e.g. `// ── Helpers`) ends it.
  const anyMarker = [...program.matchAll(/^\/\/ ── .*$/gm)].map((m) => m.index);
  const marks = [...program.matchAll(/^\/\/ ── (\d+)\. ([^─]+?) ─+$/gm)];
  marks.forEach((m) => {
    const start = m.index + m[0].length + 1;
    const end = anyMarker.find((i) => i > m.index) ?? program.length;
    sections[m[1]] = {title: m[2].trim(), code: program.slice(start, end).replace(/\s+$/, '')};
    for (const line of sections[m[1]].code.split('\n').filter((l) => l.length > 78)) {
      console.warn(`  ${name} §${m[1]}: ${line.length} chars (max 78): ${line.trim()}`);
    }
  });

  const read = (f) => readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
  const inputs = Object.fromEntries(files(join(dir, 'input'), isText).map((f) => [relative(dir, f), read(f)]));
  const outputs = Object.fromEntries(
    files(join(dir, 'output'), (f) => isText(f) && !f.endsWith('stdout.txt')).map((f) => [relative(dir, f), read(f)]),
  );

  const images = files(join(dir, 'output'), (f) => f.endsWith('.png'));
  if (images.length > 0) {
    const target = join(tutorialsDir, 'public', 'samples', name);
    mkdirSync(target, {recursive: true});
    for (const image of images) {
      copyFileSync(image, join(target, relative(join(dir, 'output'), image)));
    }
  }

  result[name] = {
    program,
    sections,
    inputs,
    outputs,
    stdout: read(capture).replace(/\s+$/, ''),
    images: images.map((f) => `samples/${name}/${relative(join(dir, 'output'), f)}`),
  };
}

const banner = '// Generated by tools/sync-samples.mjs from ../samples. Do not edit.\n';
writeFileSync(
  join(tutorialsDir, 'src', 'samples.generated.ts'),
  `${banner}/* eslint-disable */\nexport const samples = ${JSON.stringify(result, null, 2)} as const;\n`,
);
console.log(`Wrote tutorials/src/samples.generated.ts (${Object.keys(result).length} samples)`);
